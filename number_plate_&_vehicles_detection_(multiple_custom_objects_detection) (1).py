"""To determine true positives, compare each predicted box to ground truth boxes using IoU. If IoU > threshold (e.g., 0.5), it's a match."""

def compute_iou(boxA, boxB):
    # Computes IoU between two boxes [x1, y1, x2, y2]
    xA = max(boxA[0], boxB[0])
    yA = max(boxA[1], boxB[1])
    xB = min(boxA[2], boxB[2])
    yB = min(boxA[3], boxB[3])

    interArea = max(0, xB - xA) * max(0, yB - yA)
    boxAArea = (boxA[2] - boxA[0]) * (boxA[3] - boxA[1])
    boxBArea = (boxB[2] - boxB[0]) * (boxB[3] - boxB[1])

    iou = interArea / float(boxAArea + boxBArea - interArea)
    return iou

def count_true_positives(predicted_boxes, ground_truth_boxes, iou_threshold=0.5):
    matched_gt = set()
    true_positives = 0

    for pred_box in predicted_boxes:
        for i, gt_box in enumerate(ground_truth_boxes):
            if i in matched_gt:
                continue
            iou = compute_iou(pred_box, gt_box)
            if iou >= iou_threshold:
                true_positives += 1
                matched_gt.add(i)
                break

    return true_positives

