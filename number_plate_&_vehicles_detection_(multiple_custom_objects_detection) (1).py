def draw_yolo_boxes(image_path, txt_path, class_names=None):
    # Load image
    image = cv2.imread(image_path)

    # Check if image loading was successful
    if image is None:
        print(f"Error loading image: {image_path}")
        return

    image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    h, w, _ = image.shape

    # Read YOLO annotations
    try:
        with open(txt_path, 'r') as f:
            lines = f.readlines()
    except FileNotFoundError:
        print(f"Annotation file not found for image: {image_path}")
        lines = [] # Continue processing even if annotation file is missing

    # Draw bounding boxes
    for line in lines:
        parts = line.strip().split()
        if len(parts) < 5:
            print(f"Skipping invalid line in {txt_path}: {line.strip()}")
            continue

        class_id = int(parts[0])
        x_center = float(parts[1]) * w
        y_center = float(parts[2]) * h
        box_width = float(parts[3]) * w
        box_height = float(parts[4]) * h

        # Optional: confidence score if available
        confidence = float(parts[5]) if len(parts) >= 6 else None

        # Calculate top-left and bottom-right corners
        x1 = int(x_center - box_width / 2)
        y1 = int(y_center - box_height / 2)
        x2 = int(x_center + box_width / 2)
        y2 = int(y_center + box_height / 2)

        # Draw rectangle
        color = (255, 0, 0)
        cv2.rectangle(image, (x1, y1), (x2, y2), color, 2)

        # Prepare label text
        class_names = ["Bike","Bus","Car","Numberplate","Person","Truck"] # Replace with your class names
        class_label = class_names[class_id] if class_names and class_id < len(class_names) else str(class_id)
        label_text = f"{class_label} {confidence:.2f}" if confidence is not None else class_label

        # Draw label
        cv2.putText(image, label_text, (x1, y1 - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.8, color, 2)

    # Show image
    plt.figure(figsize=(10, 10))
    plt.imshow(image)
    plt.axis('off')
    plt.show()

